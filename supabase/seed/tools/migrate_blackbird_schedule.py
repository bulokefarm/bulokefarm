#!/usr/bin/env python3
"""Blackbird Logistics' delivery schedule (xlsx) -> delivery_zone rows.

    python migrate_blackbird_schedule.py "Blackbird Delivery Schedule 2024.xlsx" buloke \
        > supabase/seed/buloke/61_delivery_zones.sql

Two sheets, two layouts:

    VIC       Post Code | Suburb | Zone ID | Mon..Sat
    National  (two working columns) | Postcode | Suburb | Zone ID | Mon..Fri

A day is ticked with a Webdings 'a'; anything non-empty counts. Rows are
keyed on (carrier, postcode, suburb) — the sheet repeats a few suburbs in
different capitals, and the second is dropped rather than doubled.

Re-running replaces the carrier's schedule for the farm: when Blackbird
issue a new one, run this again and run the file again.
"""
import sys

import openpyxl

CARRIER = "Blackbird Logistics"
LAYOUT = {
    # sheet: (postcode col, suburb col, zone col, first day col, days)
    "VIC":      (0, 1, 2, 3, 6),
    "National": (2, 3, 4, 5, 5),
}
DAYS = ["mon", "tue", "wed", "thu", "fri", "sat"]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def title(s):
    """BLUE MOUNTAINS -> Blue Mountains; leaves 'Gippsland/PI' and 'GC Hinterland' alone."""
    s = " ".join(str(s).split())
    return s.title() if s.isupper() else s


def main():
    path, farm = sys.argv[1], sys.argv[-1]
    wb = openpyxl.load_workbook(path, data_only=True)
    rows, seen, skipped = [], set(), 0
    for sheet, (pc, sub, zone, d0, nd) in LAYOUT.items():
        for r in wb[sheet].iter_rows(min_row=4, values_only=True):
            if r[pc] is None or r[sub] is None or r[zone] is None:
                continue
            postcode = str(r[pc]).strip().split(".")[0].zfill(4)
            if not postcode.isdigit():
                continue
            suburb = title(r[sub])
            key = (postcode, suburb.lower())
            if key in seen:
                skipped += 1
                continue
            seen.add(key)
            ticks = [bool(r[d0 + i]) and str(r[d0 + i]).strip() != "" for i in range(nd)]
            ticks += [False] * (6 - nd)
            rows.append((sheet, postcode, suburb, title(r[zone]), ticks))

    out = sys.stdout
    out.reconfigure(encoding="utf-8", newline="\n")
    out.write(f"-- {CARRIER}: where they deliver and on which days.\n")
    out.write(f"-- Generated by seed/tools/migrate_blackbird_schedule.py from the carrier's schedule.\n")
    out.write(f"-- {len(rows)} suburbs; {skipped} repeats dropped. Do not edit by hand.\n\n")
    out.write(f"select set_config('app.farm', (select id::text from farm where slug = {q(farm)}), false);\n\n")
    out.write(f"delete from delivery_zone where farm_id = current_farm() and carrier = {q(CARRIER)};\n\n")
    for i in range(0, len(rows), 250):
        out.write("insert into delivery_zone (carrier, region, postcode, suburb, zone, "
                  + ", ".join(DAYS) + ") values\n")
        chunk = rows[i:i + 250]
        out.write(",\n".join(
            f"  ({q(CARRIER)}, {q(region)}, {q(pc)}, {q(sub)}, {q(zone)}, "
            + ", ".join("true" if t else "false" for t in ticks) + ")"
            for region, pc, sub, zone, ticks in chunk))
        out.write("\non conflict do nothing;\n\n")
    sys.stderr.write(f"{len(rows)} rows, {skipped} repeats dropped\n")


if __name__ == "__main__":
    main()
